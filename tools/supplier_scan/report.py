"""Render the approval tables (markdown) from the health + discovery CSVs.

Output is pasted into docs/ops/supplier-directory-scan-<date>.md. Each row has
an empty [ ] box for the founder to tick; the CSVs remain the source of truth
for the apply step.
"""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ORDER = {"EE": 0, "LV": 1, "LT": 2}
ZONE_ORDER = {"harjumaa": 0, "parnu": 1, "tartu": 2, "": 3}


def _esc(x):
    return (x or "").replace("|", "\\|")


def _read(p):
    return list(csv.DictReader(open(p, encoding="utf-8-sig")))


def _latest(out: Path, pattern: str):
    files = sorted(out.glob(pattern), key=lambda p: p.stat().st_mtime)
    return files[-1] if files else None


def health_tables(rows):
    lines = []
    for act in ["remove", "fix_contact", "call"]:
        sel = sorted([r for r in rows if r["action"] == act],
                     key=lambda r: (ORDER[r["country"]], ZONE_ORDER.get(r["zone"], 3), r["name"]))
        # Chains with the same finding on every branch collapse to one line.
        groups = defaultdict(list)
        for r in sel:
            key = (r["name"].split(" —")[0].split(" – ")[0], r["proposed_website"], r["proposed_email"], r["reasons"].split(" · ")[0])
            groups[key].append(r)
        lines.append(f"\n#### {act} — {len(sel)} rows\n")
        if act == "fix_contact":
            lines += ["| ok | cc | zone | row | change (current → proposed) | conf | evidence |",
                      "|---|---|---|---|---|---|---|"]
        else:
            lines += ["| ok | cc | zone | row | conf | evidence |", "|---|---|---|---|---|---|"]
        for grp in groups.values():
            r = grp[0]
            ident = f"`{r['slug']}`" if r["slug"] else f"id `{r['id']}` (no slug)"
            label = f"{_esc(r['name'])} ({ident})" if len(grp) == 1 else \
                f"{_esc(r['name'].split(' —')[0])} — {len(grp)} rows (`{grp[0]['slug']}` …)"
            ev = _esc("; ".join(r["reasons"].split(" · ")))
            if act == "fix_contact":
                ch = []
                for f, cur, pro in [("email", "current_email", "proposed_email"),
                                    ("phone", "current_phone", "proposed_phone"),
                                    ("website", "current_website", "proposed_website"),
                                    ("reg code", "current_registry_code", "proposed_registry_code")]:
                    if r[pro]:
                        ch.append(f"{f}: {_esc(r[cur]) or '∅'} → **{_esc(r[pro])}**")
                lines.append(f"| [ ] | {r['country']} | {r['zone']} | {label} | {'<br>'.join(ch)} | {r['confidence']} | {ev} |")
            else:
                lines.append(f"| [ ] | {r['country']} | {r['zone']} | {label} | {r['confidence']} | {ev} |")
    return lines


def discovery_table(rows):
    lines = ["| ok | zone | service | name | email | phone | website | reg code | town | staff | EMTAK |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| [ ] | {r['zone']} | {r['serviceTypes']} | {_esc(r['name'])} | {_esc(r['contactEmail'])} | "
            f"{_esc(r['contactPhone'])} | {_esc(r['websiteUrl'])} | [{r['registryCode']}]({r['source_ref']}) | "
            f"{r['city']} | {r['employees']} | {_esc(r['evidence'][6:70])} |")
    return lines


def code_table(dupes, suppliers):
    by_slug = {s.get("slug"): s for s in suppliers}
    cand = defaultdict(list)
    for d in dupes:
        slug = d["dup_of"].split(" ")[0]
        s = by_slug.get(slug)
        if s and not s.get("registry_code") and d["dup_by"] != "registry_code":
            cand[slug].append(d)
    lines = ["| ok | row | matched by | register entry | proposed code |", "|---|---|---|---|---|"]
    ambiguous = []
    for slug, ds in sorted(cand.items()):
        if len({d["registry_code"] for d in ds}) > 1:
            ambiguous.append(f"`{slug}` ({', '.join(_esc(d['name']) for d in ds)})")
            continue
        d = ds[0]
        lines.append(f"| [ ] | `{slug}` | {d['dup_by']} | {_esc(d['name'])} | "
                     f"[{d['registry_code']}]({d['source_ref']}) |")
    if ambiguous:
        lines.append(f"\nNot proposed — several register companies share the contact: {'; '.join(ambiguous)}.")
    return lines


def run(a):
    out = a.out
    health = _latest(out, "health-ee-lt-lv*.csv") or _latest(out, "health-*.csv")
    disc = _latest(out, "discovery-review-*.csv")
    dup = _latest(out, "discovery-already-listed-*.csv")
    suppliers = json.loads((out / "suppliers.json").read_text(encoding="utf-8"))
    hrows = _read(health)
    md = [f"<!-- generated by tools/supplier_scan/scan.py report from {health.name}, "
          f"{disc.name if disc else '-'} -->",
          "", "### Counts", "", "| country | " + " | ".join(
              ["keep", "fix_contact", "remove", "call", "skip_opt_out", "skip_inactive"]) + " |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    c = Counter((r["country"], r["action"]) for r in hrows)
    for cc in ["EE", "LV", "LT"]:
        md.append(f"| {cc} | " + " | ".join(str(c[(cc, k)]) for k in
                                           ["keep", "fix_contact", "remove", "call", "skip_opt_out",
                                            "skip_inactive"]) + " |")
    md += health_tables(hrows)
    if disc:
        md += ["", "### Discovery shortlist", ""] + discovery_table(_read(disc))
    if dup:
        md += ["", "### Registry codes for existing rows that have none", ""] + code_table(_read(dup), suppliers)
    path = out / "report-tables.md"
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {path}")
